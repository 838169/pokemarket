ALTER TABLE usuarios
    ADD COLUMN IF NOT EXISTS correo_verificado TIMESTAMP NULL,
    ADD COLUMN IF NOT EXISTS totp_secreto VARCHAR(128) NULL,
    ADD COLUMN IF NOT EXISTS totp_paso BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS totp_ventana INT UNSIGNED NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS totp_intentos TINYINT UNSIGNED NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS sesion_version INT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS codigos_cuenta (
    usuario_id INT NOT NULL,
    finalidad VARCHAR(12) NOT NULL,
    codigo_hash VARCHAR(255) NOT NULL,
    emitido INT UNSIGNED NOT NULL,
    intentos TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PRIMARY KEY (usuario_id, finalidad),
    FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE CASCADE
) ENGINE=InnoDB;
