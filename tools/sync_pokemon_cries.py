"""Import base-species game cries from the upstream archive, without 1025 HTTP requests."""
import argparse
import hashlib
import io
import json
from pathlib import Path
from urllib.request import urlopen
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "frontend/assets/audio/cries"
ARCHIVE = "https://codeload.github.com/PokeAPI/cries/zip/refs/heads/main"
VOICE = "https://play.pokemonshowdown.com/audio/cries/pikachu-starter.mp3"


def download(url):
    with urlopen(url, timeout=60) as response:
        data = response.read(100 * 1024 * 1024 + 1)
    if len(data) > 100 * 1024 * 1024:
        raise RuntimeError("Audio source exceeds the import size limit")
    return data


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pikachu-voice', type=Path, help='Previously downloaded Showdown voice file')
    args = parser.parse_args()
    archive = download(ARCHIVE)
    clips = {}
    exceptions = {}
    with ZipFile(io.BytesIO(archive)) as bundle:
        names = set(bundle.namelist())
        for pokemon_id in range(1, 1026):
            name = f"cries-main/cries/pokemon/latest/{pokemon_id}.ogg"
            if name not in names:
                raise RuntimeError(f"Missing upstream cry: {pokemon_id}")
            data = bundle.read(name)
            extension = 'ogg' if data.startswith(b'OggS') else 'mp3' if data.startswith(b'ID3') or data[:1] == b'\xff' else None
            if not extension:
                raise RuntimeError(f"Invalid audio: {pokemon_id}")
            filename = f"{pokemon_id}.{extension}"
            if extension != 'ogg':
                exceptions[pokemon_id] = filename
            clips[filename] = data
    voice = args.pikachu_voice.read_bytes() if args.pikachu_voice else download(VOICE)
    if not (voice.startswith(b"ID3") or voice[:1] == b"\xff"):
        raise RuntimeError("Invalid Pikachu voice MP3")
    clips["pikachu-voice.mp3"] = voice
    DEST.mkdir(parents=True, exist_ok=True)
    for filename, data in clips.items():
        (DEST / filename).write_bytes(data)
    (ROOT / "frontend/assets/js/pokemon-cries-catalog.js").write_text(
        "/* Generated by tools/sync_pokemon_cries.py: actual format exceptions. */\nwindow.PokeCryFiles = Object.freeze(" + json.dumps(exceptions, sort_keys=True) + ");\n", encoding="utf-8")
    print("Normalized audio format exceptions:", exceptions)
    manifest = {
        "source": ARCHIVE,
        "archive_sha256": hashlib.sha256(archive).hexdigest(),
        "pikachu_voice_source": VOICE,
        "base_species": 1025,
        "sha256": {name: hashlib.sha256(data).hexdigest() for name, data in clips.items()},
    }
    (DEST / "inventory.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Imported 1025 game cries and Pikachu voice ({sum(map(len, clips.values())):,} bytes)")


if __name__ == "__main__":
    main()
